#!/usr/bin/env python3
"""Convert semble benchmark annotations to Vera eval task format.

Downloads annotation files and repos.json from semble's GitHub repo,
converts them to Vera's BenchmarkTask JSON format, and generates a
corpus manifest (semble-corpus.toml).

Usage:
    python3 eval/scripts/convert_semble.py [--output-dir eval/tasks/semble]
"""

import argparse
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

SEMBLE_VERSION = "0.5.5"
SEMBLE_COMMIT = "921849164e2632dd4f0e1c1370f82cfe15ed6d6c"
EXPECTED_REPO_COUNT = 63
EXPECTED_TASK_COUNT = 1251
EXPECTED_REPOS_SHA256 = "fd178d28fdb98ef774d9d2b8169b34812917bde4ca57c5f7c73a1e34dfc70b1b"
EXPECTED_TASKS_SHA256 = "6d8befaa3c19211ef6c3df7d0aa7bb1711670ed32f9b0258c289909cdb5b58de"
SEMBLE_RAW = f"https://raw.githubusercontent.com/MinishLab/semble/{SEMBLE_COMMIT}/benchmarks"
REPOS_URL = f"{SEMBLE_RAW}/repos.json"
ANNOTATIONS_URL = f"{SEMBLE_RAW}/annotations"

CATEGORY_MAP = {
    "symbol": "symbol_lookup",
    "semantic": "intent",
    "architecture": "cross_file",
}


def fetch_json(url: str):
    with urllib.request.urlopen(url) as resp:
        content = resp.read()
    return json.loads(content), hashlib.sha256(content).hexdigest()


def tasks_sha256(tasks: list[dict]) -> str:
    payload = json.dumps(
        sorted(tasks, key=lambda task: task["id"]),
        sort_keys=True,
        separators=(",", ":"),
    ).encode()
    return hashlib.sha256(payload).hexdigest()


def convert_annotation(repo_name: str, entry: dict, idx: int) -> dict:
    category = CATEGORY_MAP.get(entry["category"], "intent")
    task_id = f"semble-{repo_name}-{category[:3]}-{idx:03d}"

    ground_truth = []
    for item in entry.get("relevant", []):
        if isinstance(item, str):
            ground_truth.append({
                "file_path": item,
                "line_start": 1,
                "line_end": 999999,
                "relevance": 2,
            })
        elif isinstance(item, dict):
            ground_truth.append({
                "file_path": item["path"],
                "line_start": item.get("start_line", 1),
                "line_end": item.get("end_line", 999999),
                "relevance": 2,
            })

    for item in entry.get("secondary", []):
        if isinstance(item, str):
            ground_truth.append({
                "file_path": item,
                "line_start": 1,
                "line_end": 999999,
                "relevance": 1,
            })
        elif isinstance(item, dict):
            ground_truth.append({
                "file_path": item["path"],
                "line_start": item.get("start_line", 1),
                "line_end": item.get("end_line", 999999),
                "relevance": 1,
            })

    return {
        "id": task_id,
        "query": entry["query"],
        "category": category,
        "repo": repo_name,
        "ground_truth": ground_truth,
        "description": f"[semble:{entry['category']}] {entry['query']}",
    }


def generate_corpus_toml(repos: list[dict], output_path: Path, task_count: int, tasks_hash: str):
    lines = [
        '# Semble benchmark corpus (auto-generated by convert_semble.py)',
        '#',
        '# 63 repos across 19 languages, pinned to semble benchmark revisions.',
        '',
        '[corpus]',
        'version = 1',
        'description = "Semble benchmark corpus for cross-tool evaluation"',
        'clone_root = ".bench/semble-repos"',
        '',
        '[semble]',
        f'version = "{SEMBLE_VERSION}"',
        f'commit = "{SEMBLE_COMMIT}"',
        f'task_count = {task_count}',
        f'tasks_sha256 = "{tasks_hash}"',
        '',
    ]
    for repo in repos:
        lines.append('[[repos]]')
        lines.append(f'name = "{repo["name"]}"')
        lines.append(f'url = "{repo["url"]}"')
        lines.append(f'commit = "{repo["revision"]}"')
        lines.append(f'language = "{repo["language"]}"')
        lines.append('description = "semble benchmark repo"')
        if repo.get("benchmark_root"):
            lines.append(f'benchmark_root = "{repo["benchmark_root"]}"')
        lines.append('')

    output_path.write_text('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description="Convert semble benchmarks to Vera format")
    parser.add_argument(
        "--output-dir",
        default="eval/tasks/semble",
        help="Output directory for Vera task JSON files",
    )
    parser.add_argument(
        "--corpus-output",
        default="eval/semble-corpus.toml",
        help="Output path for semble corpus manifest",
    )
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    print("Fetching semble repos.json...", file=sys.stderr)
    repos, repos_hash = fetch_json(REPOS_URL)
    if len(repos) != EXPECTED_REPO_COUNT or repos_hash != EXPECTED_REPOS_SHA256:
        raise SystemExit(
            "Semble repos.json does not match the pinned v0.5.5 snapshot "
            f"({len(repos)} repos, sha256:{repos_hash})"
        )
    print(f"  Found {len(repos)} repos", file=sys.stderr)

    converted_repos = []
    converted_tasks = []
    total_tasks = 0
    per_category = {"symbol_lookup": 0, "intent": 0, "cross_file": 0}

    for repo in repos:
        name = repo["name"]
        out_file = output_dir / f"{name}.json"
        url = f"{ANNOTATIONS_URL}/{name}.json"
        print(f"  Converting {name}...", file=sys.stderr, end=" ")

        try:
            annotations, _ = fetch_json(url)
        except Exception as e:
            out_file.unlink(missing_ok=True)
            print(f"SKIP ({e})", file=sys.stderr)
            continue

        tasks = []
        for idx, entry in enumerate(annotations, 1):
            task = convert_annotation(name, entry, idx)
            tasks.append(task)
            cat = task["category"]
            per_category[cat] = per_category.get(cat, 0) + 1

        out_file.write_text(json.dumps(tasks, indent=2) + "\n")
        converted_repos.append(repo)
        converted_tasks.extend(tasks)
        total_tasks += len(tasks)
        print(f"{len(tasks)} tasks", file=sys.stderr)

    print(
        f"\nTotal: {total_tasks} tasks across {len(converted_repos)} repos",
        file=sys.stderr,
    )
    for cat, count in sorted(per_category.items()):
        print(f"  {cat}: {count}", file=sys.stderr)

    converted_hash = tasks_sha256(converted_tasks)
    if total_tasks != EXPECTED_TASK_COUNT or converted_hash != EXPECTED_TASKS_SHA256:
        raise SystemExit(
            "Converted tasks do not match the pinned Semble v0.5.5 snapshot "
            f"({total_tasks} tasks, sha256:{converted_hash})"
        )

    corpus_path = Path(args.corpus_output)
    generate_corpus_toml(converted_repos, corpus_path, total_tasks, converted_hash)
    print(f"\nCorpus manifest: {corpus_path}", file=sys.stderr)
    print(f"Task files: {output_dir}/", file=sys.stderr)


if __name__ == "__main__":
    main()
